/** ponytail: mock visual hasta API. Solo San Miguel trae el desglose del diseño. */
function detalleBasico(
  ventas: number,
  gastos: number,
  utilidad: number,
): RentabilidadSucursalDetalle {
  const pct = (monto: number) => Math.round((Math.abs(monto) / ventas) * 1000) / 10;
  const signo = utilidad < 0 ? -1 : 1;
  return {
    cxcVencido: 0,
    cxpVencido: 0,
    puente: [
      { etiqueta: 'Ventas', monto: ventas, pct: 100 },
      { etiqueta: 'Gastos', monto: -gastos, pct: -pct(gastos) },
      { etiqueta: 'Utilidad', monto: utilidad, pct: signo * pct(utilidad) },
    ],
    productos: [],
    clientes: [],
    devolucionesTotal: 0,
    devoluciones: [],
  };
}

